// Writes assets/spilno.tokens.txt: the theme roles (--ds-*) the compiled
// plugin CSS reads and does not declare itself. The theme must provide every
// one of them; `wp spilno doctor` and the stand check it.
import { readFileSync, writeFileSync } from 'node:fs';

const css = readFileSync( new URL( '../assets/spilno.css', import.meta.url ), 'utf8' );
const used = new Set( [ ...css.matchAll( /var\(\s*(--ds-[a-z0-9-]+)/g ) ].map( ( m ) => m[ 1 ] ) );
const own = new Set( [ ...css.matchAll( /(--ds-[a-z0-9-]+)\s*:/g ) ].map( ( m ) => m[ 1 ] ) );
const roles = [ ...used ].filter( ( name ) => ! own.has( name ) ).sort();

writeFileSync(
	new URL( '../assets/spilno.tokens.txt', import.meta.url ),
	'# Theme roles read by assets/spilno.css (generated by tools/tokens.mjs).\n' + roles.join( '\n' ) + '\n'
);
console.log( `spilno.tokens.txt: ${ roles.length } roles` );
